                    'id_pengguna' => $pengguna->id,
                    'nama_lengkap' => $dataSlip['inisial'],
                    'persentase_komisi_bp' => 1000,
                    'potongan_bpjs_bulanan' => 129000,
                ],
            );

            $truk = Truk::updateOrCreate(
                ['nomor_polisi' => $dataSlip['plat']],
                [
                    'merek_model' => 'HINO PUTIH',
                ],
            );

            // Hapus ritase lama agar seeder aman dijalankan berulang.
            Ritase::where('id_periode_gaji', $periodeGaji->id)
                ->where('id_karyawan', $karyawan->id)
                ->delete();

            foreach ($dataSlip['ritase'] as $dataRitase) {
                Ritase::create([
                    'id_periode_gaji' => $periodeGaji->id,
                    'id_karyawan' => $karyawan->id,
                    'id_truk' => $truk->id,
                    'id_rute' => $rute->id,
                    'tanggal_ritase' => $dataRitase['tanggal'],
                    'jumlah_rit' => 1,
                    'tonase_kg' => $dataRitase['tonase_kg'],
                    'volume_liter' => null,
                    'tarif_per_ton' => 150000,
                    'total_angkutan' => $dataRitase['total_angkutan'],
                    'uang_jalan' => $dataRitase['uang_jalan'],
                ]);
            }

            Penggajian::updateOrCreate(
                [
                    'id_periode_gaji' => $periodeGaji->id,
                    'id_karyawan' => $karyawan->id,
                ],
                array_merge($dataSlip['penggajian'], [
                    'id_truk' => $truk->id,
                ]),
            );
        }
    }
